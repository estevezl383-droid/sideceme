import assert from 'node:assert/strict';
import {estadoRegistro,notaConformidad,botonConformidad,sinCalificar} from '../efm-campo/conformidad.mjs';
import {situacionConformidades,panelConformidades} from '../efm-campo/seguimiento.mjs';
const r={id:'R',cursante_id:'TEST',organizacion_id:'O',revision:1,prueba:'aerobica',valor:927,calculo:{nota:null,motivo:'TIEMPO MEJOR QUE PRIMERA CELDA: VALIDAR TOPE'},conformidad:{confirmado_en:'2026-11-03T12:00:00Z'}};
assert.equal(estadoRegistro(r),'sin-calificar');
assert(notaConformidad(r).includes(r.calculo.motivo));
assert(!notaConformidad(r).includes('efmc-conformidad conforme'));
assert(botonConformidad(r,'aerobica').includes('efmc-confirm-action sin-calificar'));
assert(botonConformidad(r,'aerobica').includes('disabled'));
for(const nota of [null,undefined,NaN,Infinity,'100',-1,101])assert(sinCalificar({...r,calculo:{nota}}));
for(const nota of [0,100,71.5])assert.equal(estadoRegistro({...r,calculo:{nota}}),'conforme');
assert.equal(estadoRegistro({...r,calculo:{nota:0},conformidad:null}),'pendiente');
assert.equal(estadoRegistro(null),'sin-registro');
assert.equal(sinCalificar({...r,prueba:'barras'}),false);
assert.equal(sinCalificar({...r,calculo:{estado:'NO_REALIZO',nota:null}}),false);
assert(!notaConformidad({...r,calculo:{nota:null,motivo:'<script>test</script>'}}).includes('<script>'));
const d={organizaciones:[{id:'O',grupos:[{alumnos:['TEST']}]}],cursantes:[{id:'TEST'}],registros:[r]};
assert.equal(situacionConformidades(d).sinCalificar,1);
assert.equal(situacionConformidades(d).conformes,1);
assert(panelConformidades(d).includes('data-monitor-count="sin-calificar">1'));
d.registros.push({...r,id:'R2',revision:2,calculo:{nota:100},conformidad:null});
assert.equal(situacionConformidades(d).sinCalificar,0);
assert.equal(situacionConformidades(d).conformes,0);
console.log('Calificación pendiente: ámbar aun con conformidad, motivo visible y seguro, cero válido, barras, novedades e historial: OK');
