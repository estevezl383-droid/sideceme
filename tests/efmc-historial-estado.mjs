import assert from 'node:assert/strict';
import {calificacionRevision,calificacionVigente,revisionActual,tieneNota} from '../efm-campo/historial-estado.mjs';
const original={id:'original',organizacion_id:'diagnostica',cursante_id:'FICTICIO',fecha:'2026-11-03',prueba:'aerobica',valor:997,revision:1,calculo:{nota:null},conformidad:{confirmado_en:'2026-11-03T10:00:00Z'}};
const corregida={...original,id:'corregida',revision:2,calculo:{nota:100,recalculo:{registro_origen:original.id}},conformidad:null};
const records=[original,corregida],before=JSON.stringify(records);
assert.equal(revisionActual(original,records).id,corregida.id);
assert.match(calificacionRevision(original,records),/SUBSANADA/);
assert.match(calificacionRevision(original,records),/Nota vigente: <b>100 \/ 100/);
assert(!calificacionRevision(original,records).includes('PENDIENTE'));
assert.equal(calificacionRevision(corregida,records),'100');
const html=calificacionVigente(corregida,records);
assert.match(html,/grade calificada/);assert.match(html,/100 \/ 100/);
assert.match(html,/Conformidad de esta revisión pendiente/);assert.match(html,/La marca anterior fue confirmada/);
assert(!html.includes('✓ Conformidad'));assert.equal(corregida.conformidad,null);
assert.equal(calificacionRevision(original,[original]),'PENDIENTE DE CALIFICACIÓN');
for(const change of [{organizacion_id:'otra'},{cursante_id:'otra'},{fecha:'2026-11-04'},{prueba:'abdominales'}])assert.equal(calificacionRevision(original,[original,{...corregida,...change}]),'PENDIENTE DE CALIFICACIÓN');
assert(tieneNota({...corregida,calculo:{nota:0}}));assert.equal(calificacionRevision({...corregida,calculo:{nota:0}},records),'0');
assert.equal(calificacionRevision({...original,calculo:{estado:'NO_REALIZO',nota:null}},records),'NO REALIZÓ');
assert(!tieneNota({...corregida,calculo:{nota:'100'}}));assert(!tieneNota({...corregida,calculo:{nota:101}}));
const confirmada={...corregida,calculo:{nota:79},conformidad:{confirmado_en:'2026-11-03T18:33:49Z'}};
assert(!calificacionVigente(confirmada,[original,confirmada]).includes('pendiente'));
assert.match(calificacionVigente(confirmada,[original,confirmada]),/79 \/ 100/);
assert.equal(before,JSON.stringify(records));
console.log('Revisiones subsanadas sin pendientes falsos, nota cero válida, separación de evaluación/alumno/fecha/prueba, conformidad real preservada y no realizada: OK');
